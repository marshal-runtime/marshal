def run_json(command: list[str]) -> Any:
    result = subprocess.run(
        command,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or "Command failed")
    return json.loads(result.stdout)


def gh_graphql(query: str, variables: dict[str, Any]) -> Any:
    command = ["gh", "api", "graphql", "-f", f"query={query}"]
    for key, value in variables.items():
        if value is None:
            continue
        command.extend(["-F", f"{key}={value}"])
    response = run_json(command)
    errors = response.get("errors")
    if errors:
        messages = "; ".join(error.get("message", "unknown") for error in errors)
        raise RuntimeError(f"GraphQL errors: {messages}")
    if response.get("data") is None:
        raise RuntimeError("GraphQL response missing data")
    return response


def resolve_repo(repo_arg: str | None) -> tuple[str, str]:
    repo_value = repo_arg or DEFAULT_REPO
    if "/" not in repo_value:
        raise ValueError("--repo must be in owner/name form")
    owner, name = repo_value.split("/", 1)
    return owner, name


def normalize_body(body: str) -> str:
    return re.sub(r"\s+", " ", body).strip()


def is_human_login(login: str | None) -> bool:
    if not login:
        return False
    lowered = login.lower()
    return (
        lowered not in AUTO_EXCLUDE_LOGINS
        and not lowered.endswith(BOT_LOGIN_SUFFIX)
        and not any(lowered.startswith(prefix) for prefix in AUTO_EXCLUDE_LOGIN_PREFIXES)
    )


def body_has_excluded_signature(body: str) -> bool:
    lowered = body.lower()
    return any(snippet in lowered for snippet in AUTO_EXCLUDE_BODY_SNIPPETS)


def load_reviewer_profiles(path: Path) -> dict[str, dict[str, Any]]:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise ValueError(f"Reviewer profiles file not found: {path}") from exc
    except json.JSONDecodeError as exc:
        raise ValueError(f"Reviewer profiles file is not valid JSON: {path}: {exc}") from exc

    reviewers = raw.get("reviewers")
    if not isinstance(reviewers, list):
        raise ValueError(f"Reviewer profiles file must contain a 'reviewers' array: {path}")

    profiles: dict[str, dict[str, Any]] = {}
    for index, reviewer in enumerate(reviewers):
        if not isinstance(reviewer, dict):
            raise ValueError(f"Reviewer profile at index {index} must be an object")

        login = reviewer.get("login")
        if not isinstance(login, str) or not login.strip():
            raise ValueError(f"Reviewer profile at index {index} is missing a non-empty 'login'")

        normalized_login = login.strip().lower()
        if normalized_login in profiles:
            raise ValueError(f"Reviewer profiles file contains duplicate login: {normalized_login}")

        profiles[normalized_login] = {
            "login": login.strip(),
            "displayName": reviewer.get("displayName"),
            "priority": reviewer.get("priority"),
            "includeInDefaultAuthorFilter": bool(reviewer.get("includeInDefaultAuthorFilter", False)),
        }

    return profiles


def annotate_reviewer_profile(record: dict[str, Any], reviewer_profiles: dict[str, dict[str, Any]]) -> None:
    reviewer = (record.get("ReviewAuthor") or "").lower()
    profile = reviewer_profiles.get(reviewer)

    record["ReviewerDisplayName"] = profile.get("displayName") if profile else None
    record["ReviewerPriority"] = profile.get("priority") if profile else None
    record["ReviewerInDefaultAuthorFilter"] = bool(profile and profile.get("includeInDefaultAuthorFilter"))
    record["IsTopPriorityReviewer"] = bool(
        profile and profile.get("priority") == TOP_PRIORITY_REVIEWER_PRIORITY
    )


def map_authors_filter(
    author_arg: str | None,
    reviewer_profiles: dict[str, dict[str, Any]],
) -> list[str] | None:
    if author_arg == "default":
        default_authors = sorted(
            profile["login"].lower()
            for profile in reviewer_profiles.values()
            if profile.get("includeInDefaultAuthorFilter")
        )
        return default_authors or list(DEFAULT_AUTHORS)
    if author_arg:
        return [login.strip().lower() for login in author_arg.split(",") if login.strip()]
    return None


def parse_date_window(args: argparse.Namespace) -> tuple[date, date]:
    now = datetime.now(timezone.utc).date()
    end_date = date.fromisoformat(args.end_date) if args.end_date else now
    start_date = date.fromisoformat(args.start_date) if args.start_date else end_date - timedelta(days=args.days)
    if start_date >= end_date:
        raise ValueError("start date must be earlier than end date")
    return start_date, end_date


def build_search_query(owner: str, repo: str, base_branch: str, start_date: date, end_date: date) -> str:
    inclusive_end = end_date - timedelta(days=1)
    if inclusive_end < start_date:
        raise ValueError("date window is empty")
    return (
        f"repo:{owner}/{repo} "
        "is:pr "
        "is:merged "
        f"base:{base_branch} "
        f"merged:{start_date.isoformat()}..{inclusive_end.isoformat()}"
    )


def iter_merged_pull_requests(owner: str, repo: str, base_branch: str, start_date: date, end_date: date) -> list[dict[str, Any]]:
    search_query = build_search_query(owner, repo, base_branch, start_date, end_date)
    cursor: str | None = None
    pull_requests: list[dict[str, Any]] = []

    while True:
        response = gh_graphql(
            SEARCH_QUERY,
            {
                "searchQuery": search_query,
                "cursor": cursor,
                "searchPageSize": SEARCH_PAGE_SIZE,
            },
        )
        search = response["data"]["search"]
        for node in search["nodes"]:
            if node:
                pull_requests.append(node)
        if not search["pageInfo"]["hasNextPage"]:
            break
        cursor = search["pageInfo"]["endCursor"]

    pull_requests.sort(key=lambda pr: pr["number"])
    return pull_requests


def extract_threads(owner: str, repo: str, pull_request_number: int) -> list[dict[str, Any]]:
    cursor: str | None = None
    extracted: list[dict[str, Any]] = []

    while True:
        response = gh_graphql(
            THREADS_QUERY,
            {
                "owner": owner,
                "name": repo,
                "number": pull_request_number,
                "cursor": cursor,
                "threadPageSize": THREAD_PAGE_SIZE,
            },
        )
        pull_request = response["data"]["repository"]["pullRequest"]
        if not pull_request:
            break

        threads = pull_request["reviewThreads"]
        for thread in threads["nodes"]:
            comments = thread["comments"]["nodes"]
            if not comments:
                continue
            comment = comments[0]
            review = comment.get("pullRequestReview") or {}
            extracted.append(
                {
                    "PullRequestNumber": pull_request["number"],
                    "PullRequestTitle": pull_request["title"],
                    "PullRequestUrl": pull_request["url"],
                    "MergedAt": pull_request["mergedAt"],
                    "BaseBranch": pull_request["baseRefName"],
                    "HeadBranch": pull_request["headRefName"],
                    "PullRequestAuthor": (pull_request.get("author") or {}).get("login"),
                    "CommentId": comment["databaseId"],
                    "Comment": comment["body"],
                    "filePath": thread["path"],
                    "DiffHunk": comment.get("diffHunk") or "",
                    "ReviewAuthor": (comment.get("author") or {}).get("login"),
                    "AuthorAssociation": comment.get("authorAssociation"),
                    "CommentUrl": comment.get("url"),
                    "CreatedAt": comment.get("createdAt"),
                    "Line": comment.get("line"),
                    "OriginalLine": comment.get("originalLine"),
                    "CommitOid": (comment.get("commit") or {}).get("oid"),
                    "OriginalCommitOid": (comment.get("originalCommit") or {}).get("oid"),
                    "ReviewState": review.get("state"),
                    "ReviewSubmittedAt": review.get("submittedAt"),
                    "IsResolved": thread.get("isResolved", False),
                    "IsOutdated": thread.get("isOutdated", False),
                    "CommentKind": "review-thread",
                }
            )

        if not threads["pageInfo"]["hasNextPage"]:
            break
        cursor = threads["pageInfo"]["endCursor"]

    return extracted


def extract_issue_comments(owner: str, repo: str, pr_number: int, pr_meta: dict[str, Any]) -> list[dict[str, Any]]:
    """Extract top-level PR discussion comments (issue-level) via GraphQL."""
    cursor: str | None = None
    extracted: list[dict[str, Any]] = []

    while True:
        response = gh_graphql(
            ISSUE_COMMENTS_QUERY,
            {
                "owner": owner,
                "name": repo,
                "number": pr_number,
                "cursor": cursor,
            },
        )
        pull_request = response["data"]["repository"]["pullRequest"]
        if not pull_request:
            break

        comments_page = pull_request["comments"]
        for comment in comments_page["nodes"]:
            extracted.append(
                {
                    "PullRequestNumber": pull_request["number"],
                    "PullRequestTitle": pull_request["title"],
                    "PullRequestUrl": pull_request["url"],
                    "MergedAt": pull_request["mergedAt"],
                    "BaseBranch": pull_request["baseRefName"],
                    "HeadBranch": pull_request["headRefName"],
                    "PullRequestAuthor": (pull_request.get("author") or {}).get("login"),
                    "CommentId": comment["databaseId"],
                    "Comment": comment["body"],
                    "filePath": FILEPATH_ISSUE_LEVEL,
                    "DiffHunk": "",
                    "ReviewAuthor": (comment.get("author") or {}).get("login"),
                    "AuthorAssociation": comment.get("authorAssociation"),
                    "CommentUrl": comment.get("url"),
                    "CreatedAt": comment.get("createdAt"),
                    "Line": None,
                    "OriginalLine": None,
                    "CommitOid": None,
                    "OriginalCommitOid": None,
                    "ReviewState": None,
                    "ReviewSubmittedAt": None,
                    "IsResolved": False,
                    "IsOutdated": False,
                    "CommentKind": "issue",
                }
            )

        if not comments_page["pageInfo"]["hasNextPage"]:
            break
        cursor = comments_page["pageInfo"]["endCursor"]

    return extracted


def extract_review_bodies(owner: str, repo: str, pr_number: int, pr_meta: dict[str, Any]) -> list[dict[str, Any]]:
    """Extract formal review bodies (COMMENTED/APPROVED/CHANGES_REQUESTED with non-empty body)."""
    cursor: str | None = None
    extracted: list[dict[str, Any]] = []

    while True:
        response = gh_graphql(
            PR_REVIEWS_QUERY,
            {
                "owner": owner,
                "name": repo,
                "number": pr_number,
                "cursor": cursor,
            },
        )
        pull_request = response["data"]["repository"]["pullRequest"]
        if not pull_request:
            break

        reviews_page = pull_request["reviews"]
        for review in reviews_page["nodes"]:
            # Skip reviews with empty body — they're just approval clicks
            body = review.get("body") or ""
            if not body.strip():
                continue
            extracted.append(
                {
                    "PullRequestNumber": pull_request["number"],
                    "PullRequestTitle": pull_request["title"],
                    "PullRequestUrl": pull_request["url"],
                    "MergedAt": pull_request["mergedAt"],
                    "BaseBranch": pull_request["baseRefName"],
                    "HeadBranch": pull_request["headRefName"],
                    "PullRequestAuthor": (pull_request.get("author") or {}).get("login"),
                    "CommentId": review["databaseId"],
                    "Comment": body,
                    "filePath": FILEPATH_REVIEW_BODY,
                    "DiffHunk": "",
                    "ReviewAuthor": (review.get("author") or {}).get("login"),
                    "AuthorAssociation": review.get("authorAssociation"),
                    "CommentUrl": review.get("url"),
                    "CreatedAt": review.get("submittedAt"),
                    "Line": None,
                    "OriginalLine": None,
                    "CommitOid": (review.get("commit") or {}).get("oid"),
                    "OriginalCommitOid": None,
                    "ReviewState": review.get("state"),
                    "ReviewSubmittedAt": review.get("submittedAt"),
                    "IsResolved": False,
                    "IsOutdated": False,
                    "CommentKind": "review-body",
                }
            )

        if not reviews_page["pageInfo"]["hasNextPage"]:
            break
        cursor = reviews_page["pageInfo"]["endCursor"]

    return extracted


def passes_filters(record: dict[str, Any], allowed_authors: list[str] | None) -> bool:
    reviewer = record.get("ReviewAuthor")
    pr_author = (record.get("PullRequestAuthor") or "").lower()
    comment = record.get("Comment") or ""
    file_path = record.get("filePath") or ""

    if not file_path:
        return False
    if not is_human_login(reviewer):
        return False
    if reviewer and reviewer.lower() == pr_author:
        return False
    if allowed_authors and reviewer and reviewer.lower() not in allowed_authors:
        return False
    if body_has_excluded_signature(comment):
        return False
    if len(normalize_body(comment)) < MIN_COMMENT_LENGTH:
        return False
    return True


def summarize(records: list[dict[str, Any]]) -> None:
    pr_count = len({record["PullRequestNumber"] for record in records})
    resolved_count = sum(1 for record in records if record.get("IsResolved"))
    outdated_count = sum(1 for record in records if record.get("IsOutdated"))
    top_priority_records = sum(1 for record in records if record.get("IsTopPriorityReviewer"))
    top_priority_prs = len(
        {record["PullRequestNumber"] for record in records if record.get("IsTopPriorityReviewer")}
    )
    reviewers = Counter((record.get("ReviewAuthor") or "(unknown)") for record in records)
    channel_counts = Counter((record.get("CommentKind") or "(unknown)") for record in records)
    extensions = Counter()

    for record in records:
        file_path = record.get("filePath") or ""
        if file_path in (FILEPATH_ISSUE_LEVEL, FILEPATH_REVIEW_BODY):
            extensions[file_path] += 1
        elif "." in file_path:
            extensions[file_path.rsplit(".", 1)[-1].lower()] += 1
        else:
            extensions["(none)"] += 1

    print()
    print("Results:")
    print(f"  Comments: {len(records)}")
    print(f"  PRs: {pr_count}")
    print(f"  Resolved threads: {resolved_count}")
    print(f"  Outdated threads: {outdated_count}")
    print(f"  Top-priority reviewer comments: {top_priority_records}")
    print(f"  Top-priority reviewer PRs: {top_priority_prs}")
    print("\n  By channel:")
    for channel in ("review-thread", "issue", "review-body"):
        print(f"    {channel}: {channel_counts.get(channel, 0)}")
    print("\n  Top reviewers:")
    if reviewers:
        for reviewer, count in reviewers.most_common(10):
            print(f"    {reviewer}: {count}")
    else:
        print("    (none)")
    print("\n  Top file extensions:")
    if extensions:
        for extension, count in extensions.most_common(10):
            print(f"    .{extension}: {count}")
    else:
        print("    (none)")


def parse_channels(channels_arg: str) -> set[str]:
    channels = {c.strip() for c in channels_arg.split(",") if c.strip()}
    invalid = channels - VALID_CHANNELS
    if invalid:
        raise ValueError(
            f"Invalid channel(s): {', '.join(sorted(invalid))}. "
            f"Valid channels: {', '.join(sorted(VALID_CHANNELS))}"
        )
    if not channels:
        raise ValueError("--channels must specify at least one channel")
    return channels


def main() -> None:
    parser = argparse.ArgumentParser(description="Extract human GitHub review comments for rule discovery")
    parser.add_argument("--repo", default=DEFAULT_REPO, help=f"GitHub repo in owner/name form (default: {DEFAULT_REPO})")
    parser.add_argument("--base-branch", default=DEFAULT_BASE_BRANCH, help="Base branch to target (default: main)")
    parser.add_argument("--start-date", default=None, help="Start date inclusive (YYYY-MM-DD)")
    parser.add_argument("--end-date", default=None, help="End date exclusive (YYYY-MM-DD)")
    parser.add_argument("--days", type=int, default=DEFAULT_DAYS, help=f"Days to look back (default: {DEFAULT_DAYS})")
    parser.add_argument("--author", default=None, help="Comma-separated reviewer logins to filter by, or 'default'")
    parser.add_argument(
        "--reviewer-profiles",
        default=None,
        help="Optional path to reviewer profile JSON (default: none)",
    )
    parser.add_argument("--sample", type=int, default=None, help="Deterministic sample size after filtering")
    parser.add_argument("--output", default=None, help="Output file (default: human-comments-{start}_{end}.json)")
    parser.add_argument(
        "--channels",
        default=DEFAULT_CHANNELS,
        help=(
            f"Comma-separated channels to mine (default: {DEFAULT_CHANNELS}). "
            f"Valid: {', '.join(sorted(VALID_CHANNELS))}"
        ),
    )
    args = parser.parse_args()

    start_date, end_date = parse_date_window(args)
    owner, repo = resolve_repo(args.repo)
    reviewer_profiles = load_reviewer_profiles(Path(args.reviewer_profiles)) if args.reviewer_profiles else {}
    allowed_authors = map_authors_filter(args.author, reviewer_profiles)
    channels = parse_channels(args.channels)

    output_file = args.output or f"human-comments-{start_date.isoformat()}_{end_date.isoformat()}.json"

    print(f"Repo: {owner}/{repo}")
    print(f"Window: {start_date.isoformat()} to {end_date.isoformat()} (end exclusive)")
    print(f"Base branch: {args.base_branch}")
    print(f"Channels: {', '.join(sorted(channels))}")
    default_profile_count = sum(
        1 for profile in reviewer_profiles.values() if profile.get("includeInDefaultAuthorFilter")
    )
    print(
        "Reviewer profiles: "
        f"{args.reviewer_profiles or 'none'} ({len(reviewer_profiles)} configured, "
        f"{default_profile_count} in default allowlist)"
    )
    if allowed_authors:
        print(f"Author filter: {', '.join(allowed_authors)}")
    else:
        print("Author filter: disabled (all reviewers)")

    pull_requests = iter_merged_pull_requests(owner, repo, args.base_branch, start_date, end_date)
    print(f"Merged PRs in scope: {len(pull_requests)}")

    records: list[dict[str, Any]] = []
    for pull_request in pull_requests:
        pr_number = pull_request["number"]

        if "review-thread" in channels:
            print(f"  Fetching review threads for PR #{pr_number}...", file=sys.stderr)
            extracted = extract_threads(owner, repo, pr_number)
            for record in extracted:
                annotate_reviewer_profile(record, reviewer_profiles)
                if passes_filters(record, allowed_authors):
                    records.append(record)

        if "issue" in channels:
            print(f"  Fetching issue comments for PR #{pr_number}...", file=sys.stderr)
            extracted = extract_issue_comments(owner, repo, pr_number, pull_request)
            for record in extracted:
                annotate_reviewer_profile(record, reviewer_profiles)
                if passes_filters(record, allowed_authors):
                    records.append(record)

        if "review-body" in channels:
            print(f"  Fetching review bodies for PR #{pr_number}...", file=sys.stderr)
            extracted = extract_review_bodies(owner, repo, pr_number, pull_request)
            for record in extracted:
                annotate_reviewer_profile(record, reviewer_profiles)
                if passes_filters(record, allowed_authors):
                    records.append(record)

    records.sort(key=lambda record: (record["PullRequestNumber"], record.get("CommentId") or 0))

    if args.sample:
        rng = random.Random(0)
        sample_size = min(args.sample, len(records))
        records = sorted(
            rng.sample(records, sample_size),
            key=lambda record: (record["PullRequestNumber"], record.get("CommentId") or 0),
        )
        print(f"Sampled records: {sample_size}")

    summarize(records)

    with Path(output_file).open("w", encoding="utf-8") as handle:
        json.dump(records, handle, indent=2, ensure_ascii=False)
    print()
    print(f"Written to: {output_file}")


