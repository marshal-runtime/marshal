#!/usr/bin/env python3
# marshal-owned
"""Extract human GitHub review comments for rule discovery.

This is the GitHub port of an earlier review-comment extractor. It finds merged pull
requests targeting OmerMachluf/marshal main, walks their review threads, issue-level comments,
and formal review bodies, and emits one record per qualifying comment.

Channels mined by default:
  - review-thread  Inline code-anchored review comments (reviewThreads)
  - issue          Top-level PR discussion comments (issues/{n}/comments)
  - review-body    Formal review bodies with COMMENTED/APPROVED/CHANGES_REQUESTED state

Filters:
  - merged PRs only
  - base branch defaults to main
  - review-thread: thread-opening comment only
  - human accounts only (no bots)
  - no self-comments from the PR author
  - review-thread: code-anchored comments only (has path)
  - >= 20 chars after whitespace normalization

Usage:
  python3 marshal-extract-human-comments.py                    # last 21 days, default repo OmerMachluf/marshal
  python3 marshal-extract-human-comments.py --days 28
  python3 marshal-extract-human-comments.py --start-date 2026-03-01 --end-date 2026-03-22
  python3 marshal-extract-human-comments.py --author default
  python3 marshal-extract-human-comments.py --author "user1,user2"
  python3 marshal-extract-human-comments.py --reviewer-profiles my-reviewer-profiles.json
  python3 marshal-extract-human-comments.py --repo OmerMachluf/marshal --output comments.json
  python3 marshal-extract-human-comments.py --channels review-thread,issue
  python3 marshal-extract-human-comments.py --channels review-thread,issue,review-body
"""

