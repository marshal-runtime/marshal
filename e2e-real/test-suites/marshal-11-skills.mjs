// Marshal-owned real-account harness.
/**
 * 11-skills: Create a Word doc and Excel spreadsheet via bundled skills.
 */
import {
  waitForReady,
  sendPrompt,
  waitForResponse,
  getLastAssistantMessage,
  screenshot,
  timestamp,
} from "../marshal-cdp-helpers.mjs";

export default {
  name: "Office Skills",
  async run({ Runtime, Page, resultsDir }) {
    let steps = 0;
    const ts = timestamp();

    await waitForReady(Runtime);
    steps++;

    // Create Word doc
    await sendPrompt(
      Runtime,
      `Create a Word document called "e2e-test-${ts}.docx" with a heading "E2E Test Report" and a paragraph saying "This document was auto-generated by Marshal's E2E test suite at ${ts}."`,
    );
    steps++;
    console.log("   ✓ Sent: create Word doc");

    await waitForResponse(Runtime, 45, 120);
    steps++;

    const response1 = await getLastAssistantMessage(Runtime);
    if (!response1) throw new Error("No response for Word doc creation");
    steps++;
    console.log(`   ✓ Docx response: "${response1.slice(0, 80)}..."`);

    await screenshot(Page, resultsDir, "11-skill-docx.png");
    console.log("   📸 11-skill-docx.png");

    // Create Excel spreadsheet
    await sendPrompt(
      Runtime,
      `Create a simple Excel spreadsheet called "e2e-test-${ts}.xlsx" with columns Name, Role, Score and these 3 rows: Alice/Engineer/95, Bob/Designer/88, Carol/PM/92.`,
    );
    steps++;

    await waitForResponse(Runtime, 45, 120);
    steps++;

    const response2 = await getLastAssistantMessage(Runtime);
    if (!response2) throw new Error("No response for Excel creation");
    steps++;
    console.log(`   ✓ Xlsx response: "${response2.slice(0, 80)}..."`);

    await screenshot(Page, resultsDir, "11-skill-xlsx.png");
    console.log("   📸 11-skill-xlsx.png");

    // Clean up
    await sendPrompt(
      Runtime,
      `Delete the files "e2e-test-${ts}.docx" and "e2e-test-${ts}.xlsx". Confirm when done.`,
    );
    steps++;

    await waitForResponse(Runtime, 20, 60);
    steps++;

    await screenshot(Page, resultsDir, "11-skills-cleaned.png");
    console.log("   📸 11-skills-cleaned.png");

    return steps;
  },
};
